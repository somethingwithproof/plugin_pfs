namespace Somethingwithproof\Pfs;

/**
 * How the reader reaches a node (decision #7, provisional). Ssh runs the
 * fixed read script through a forced command; an exporter source is a later
 * option.
 */
enum AccessMethod: string {
	case Ssh = 'ssh';

	public function label(): string {
		return match ($this) {
			self::Ssh => __('SSH forced command', 'pfs'),
		};
	}
}
